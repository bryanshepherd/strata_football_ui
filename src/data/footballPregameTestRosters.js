function buildRosterTeam(team, source) {
  const players = {};
  const jerseyIndex = {};
  const sortedPlayers = [...source.players].sort((left, right) => (
    Number(left[1]) - Number(right[1]) || String(left[0]).localeCompare(String(right[0]))
  ));

  sortedPlayers.forEach(([sourceCode, jersey, displayName, position, offPosition, defPosition, stPosition]) => {
    const fallbackCode = `${jersey}-${displayName.replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '').toUpperCase()}`;
    const playerId = `${team}-${sourceCode || fallbackCode}`;
    players[playerId] = {
      playerId,
      team,
      jersey,
      displayName,
      position,
      ...(offPosition ? { off_position: offPosition } : {}),
      ...(defPosition ? { def_position: defPosition } : {}),
      ...(stPosition ? { st_position: stPosition } : {}),
      active: true,
      sourceCode,
    };
    jerseyIndex[jersey] = [...(jerseyIndex[jersey] || []), playerId];
  });

  return {
    teamId: source.teamId,
    name: source.name,
    abbr: source.abbr,
    players,
    jerseyIndex,
  };
}

